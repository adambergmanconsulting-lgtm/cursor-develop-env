# Shared helpers for Cursor My Machines Windows autostart installers.

function Write-InstallStep {
    param([string] $Message)
    Write-Host $Message
}

function Get-AgentCmdPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\agent.cmd'
}

function Get-DefaultAutostartLogPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\worker-autostart.log'
}

function Get-DefaultStartScriptPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\start-my-machines-worker.ps1'
}

function Ensure-GitBash {
    $git = Get-Command git -ErrorAction SilentlyContinue
    if (-not $git) {
        throw @"
Git for Windows is required (includes Git Bash).
Install from https://git-scm.com/download/win then re-run this script.
"@
    }
    $bashCandidates = @(
        (Join-Path (Split-Path $git.Source -Parent) 'bash.exe'),
        'C:\Program Files\Git\bin\bash.exe',
        'C:\Program Files (x86)\Git\bin\bash.exe'
    )
    foreach ($bash in $bashCandidates) {
        if (Test-Path -LiteralPath $bash) { return }
    }
    throw 'Git is on PATH but Git Bash was not found. Reinstall Git for Windows with Git Bash.'
}

function Ensure-AgentCli {
    param([string] $AgentCmd)

    if (Test-Path -LiteralPath $AgentCmd) { return }
    Write-InstallStep 'Cursor CLI not found. Installing via cursor.com/install (win32)...'
    irm 'https://cursor.com/install?win32=true' | iex
    if (-not (Test-Path -LiteralPath $AgentCmd)) {
        throw "Install finished but agent.cmd is missing at $AgentCmd. Open a new terminal and run: agent --version"
    }
}

function Test-AgentAuth {
    param([string] $AgentCmd)

    $debug = & $AgentCmd worker debug 2>&1 | Out-String
    if ($debug -match 'Auth\s+Method\s+login' -or $debug -match 'Auth\s+Method\s+api-key' -or $debug -match 'Auth\s+Method\s+token') {
        return
    }
    if ($debug -match 'not authenticated|sign in|login required') {
        throw 'Cursor CLI is not signed in. Run: agent login'
    }
    if ($debug -notmatch 'Email\s+\S') {
        throw 'Could not verify Cursor login. Run: agent login'
    }
}

function Write-WorkerStartScript {
    param(
        [string] $Path,
        [string] $Agent,
        [string] $Root,
        [string] $Name,
        [string] $Log,
        [string] $ScopeNote
    )

    # agent.cmd always spawns a second powershell.exe without -WindowStyle Hidden,
    # which leaves a visible console. Call cursor-agent.ps1 in-process instead.
    # Task Scheduler also often ignores -WindowStyle Hidden for Interactive logon
    # tasks, so the generated script hides its own console via ShowWindow.
    $agentHome = [System.IO.Path]::GetDirectoryName($Agent).Replace("'", "''")
    $rootEsc = $Root.Replace("'", "''")
    $nameEsc = $Name.Replace("'", "''")
    $logEsc = $Log.Replace("'", "''")
    $content = @"
# Generated by cursor-develop-env installer ($ScopeNote).
`$ErrorActionPreference = 'Stop'

`$agentHome = '$agentHome'
`$agentPs1 = Join-Path `$agentHome 'cursor-agent.ps1'
`$workerRoot = '$rootEsc'
`$workerName = '$nameEsc'
`$logPath = '$logEsc'

function Write-AutostartLog {
    param([string]`$Message)
    `$line = "{0} {1}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), `$Message
    Add-Content -LiteralPath `$logPath -Value `$line -Encoding utf8
}

function Hide-AutostartConsole {
    # Task Scheduler's -WindowStyle Hidden is unreliable for Interactive tasks that
    # stay alive hosting the worker. Force-hide this console so enroll stays silent.
    if (-not ('CursorDevelopEnv.Win32' -as [type])) {
        Add-Type -Namespace CursorDevelopEnv -Name Win32 -MemberDefinition @'
[DllImport("kernel32.dll")] public static extern IntPtr GetConsoleWindow();
[DllImport("user32.dll")] public static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);
'@
    }
    `$hwnd = [CursorDevelopEnv.Win32]::GetConsoleWindow()
    if (`$hwnd -ne [IntPtr]::Zero) {
        [void][CursorDevelopEnv.Win32]::ShowWindow(`$hwnd, 0)
    }
}

function Enable-WorkerStayAwake {
    # Keep the machine from idle-sleeping while this host process runs the worker.
    # Flags are set in C# (PowerShell cannot cast 0x80000000 to UInt32).
    # Replaces the old separate CursorSelfHosted-KeepAwake logon task.
    if (-not ('CursorDevelopEnv.StayAwake' -as [type])) {
        Add-Type -Namespace CursorDevelopEnv -Name StayAwake -MemberDefinition @'
[DllImport("kernel32.dll")] private static extern uint SetThreadExecutionState(uint esFlags);
// ES_CONTINUOUS | ES_SYSTEM_REQUIRED
public static void Enable() { SetThreadExecutionState(0x80000001u); }
'@
    }
    [CursorDevelopEnv.StayAwake]::Enable()
}

Hide-AutostartConsole
Enable-WorkerStayAwake

if (-not (Test-Path -LiteralPath `$agentPs1)) {
    Write-AutostartLog "cursor-agent.ps1 missing at `$agentPs1"
    exit 1
}

if (-not (Test-Path -LiteralPath `$workerRoot)) {
    Write-AutostartLog "worker root missing at `$workerRoot"
    exit 1
}

`$workers = Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
    Where-Object { `$_.CommandLine -like '*cursor-agent*' -and `$_.CommandLine -like '*worker*' }

`$matching = `$workers | Where-Object {
    `$_.CommandLine -like "*--name `$workerName*" -and
    `$_.CommandLine -like "*`$workerRoot*"
}
if (`$matching) {
    Write-AutostartLog "worker already running name=`$workerName (pid `$(`$matching.ProcessId -join ',')); skipping"
    exit 0
}

`$others = `$workers | Where-Object {
    -not (`$_.CommandLine -like "*--name `$workerName*" -and `$_.CommandLine -like "*`$workerRoot*")
}
if (`$others) {
    Write-AutostartLog ("stopping other worker(s) so this machine has one agent (pid {0})" -f (`$others.ProcessId -join ','))
    foreach (`$proc in `$others) {
        Stop-Process -Id `$proc.ProcessId -Force -ErrorAction SilentlyContinue
    }
    Start-Sleep -Seconds 1
}

Write-AutostartLog "starting worker name=`$workerName root=`$workerRoot (silent in-process)"
Set-Location -LiteralPath `$workerRoot
# Do not redirect worker stdio — piping breaks the CLI on Windows (exits immediately).
# Console is already hidden via ShowWindow; tips stay off-screen.
& `$agentPs1 worker --name `$workerName --worker-dir `$workerRoot --idle-release-timeout 0 start
`$exit = `$LASTEXITCODE
if (`$null -eq `$exit) { `$exit = 0 }
Write-AutostartLog "worker exited with code `$exit"
exit `$exit
"@

    Set-Content -LiteralPath $Path -Value $content -Encoding utf8
}

function Register-WorkerAutostartTask {
    param(
        [string] $Name,
        [string] $ScriptPath,
        [string] $Description
    )

    # Prefer Windows PowerShell for the logon task: console hide via ShowWindow is
    # reliable there, and installers must parse under 5.1 (no ?.).
    $pwshCmd = Get-Command pwsh -ErrorAction SilentlyContinue
    if ($pwshCmd -and $env:CURSOR_DEV_AUTOSTART_PWSH -eq '1') {
        $pwsh = $pwshCmd.Source
    } else {
        $pwsh = (Get-Command powershell.exe).Source
    }

    $action = New-ScheduledTaskAction -Execute $pwsh -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$ScriptPath`""
    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
    $settings = New-ScheduledTaskSettingsSet `
        -AllowStartIfOnBatteries `
        -DontStopIfGoingOnBatteries `
        -ExecutionTimeLimit ([TimeSpan]::Zero) `
        -RestartCount 999 `
        -RestartInterval (New-TimeSpan -Minutes 5) `
        -MultipleInstances IgnoreNew
    $principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

    $existing = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if ($existing) {
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false
    }

    Register-ScheduledTask `
        -TaskName $Name `
        -Action $action `
        -Trigger $trigger `
        -Settings $settings `
        -Principal $principal `
        -Description $Description | Out-Null

    Remove-LegacyKeepAwakeTask
}

function Uninstall-WorkerAutostartTask {
    param([string] $Name)

    $existing = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if ($existing) {
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false
        Write-InstallStep "Removed scheduled task: $Name"
    } else {
        Write-InstallStep "Scheduled task not found: $Name"
    }
    Remove-LegacyKeepAwakeTask
}

function Remove-LegacyKeepAwakeTask {
    # Old cursor-my-machines enrolled a separate keep-awake PowerShell at logon.
    $legacyName = 'CursorSelfHosted-KeepAwake'
    $legacy = Get-ScheduledTask -TaskName $legacyName -ErrorAction SilentlyContinue
    if ($legacy) {
        Unregister-ScheduledTask -TaskName $legacyName -Confirm:$false
        Write-InstallStep "Removed legacy scheduled task: $legacyName"
    }

    Get-CimInstance Win32_Process -Filter "Name='powershell.exe'" -ErrorAction SilentlyContinue |
        Where-Object { $_.CommandLine -like '*keep-awake.ps1*' } |
        ForEach-Object {
            Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
            Write-InstallStep "Stopped legacy keep-awake process pid $($_.ProcessId)"
        }
}

function Set-DevelopEnvUserVars {
    param(
        [Parameter(Mandatory = $true)]
        [string] $WorkerName,
        [string] $PeerWorker
    )

    [Environment]::SetEnvironmentVariable('CURSOR_DEV_WORKER_NAME', $WorkerName, 'User')
    $env:CURSOR_DEV_WORKER_NAME = $WorkerName
    Write-InstallStep "User env CURSOR_DEV_WORKER_NAME=$WorkerName"

    if ($PeerWorker) {
        [Environment]::SetEnvironmentVariable('CURSOR_DEV_PEER_WORKER', $PeerWorker, 'User')
        $env:CURSOR_DEV_PEER_WORKER = $PeerWorker
        Write-InstallStep "User env CURSOR_DEV_PEER_WORKER=$PeerWorker"
    }
}

function Set-DevelopEnvPowerBoth {
    param(
        [string] $Scheme,
        [string] $Sub,
        [string] $Set,
        [string] $Val
    )
    powercfg /setacvalueindex $Scheme $Sub $Set $Val | Out-Null
    powercfg /setdcvalueindex $Scheme $Sub $Set $Val | Out-Null
}

function Set-DevelopEnvNeverSleep {
    # User-level always-on: My Machines only receive jobs while the PC is awake and
    # the worker is online. Sleeping until "agent activity" is not reliable for Cloud
    # Agents, so enroll configures never idle-sleep / hibernate / display / disk off.
    $schemeLine = powercfg /getactivescheme
    if ($schemeLine -notmatch '([0-9a-f-]{36})') {
        throw "Could not read active power scheme: $schemeLine"
    }
    $scheme = $Matches[1]

    powercfg /change standby-timeout-ac 0 | Out-Null
    powercfg /change standby-timeout-dc 0 | Out-Null
    powercfg /change monitor-timeout-ac 0 | Out-Null
    powercfg /change monitor-timeout-dc 0 | Out-Null
    powercfg /change hibernate-timeout-ac 0 | Out-Null
    powercfg /change hibernate-timeout-dc 0 | Out-Null
    powercfg /change disk-timeout-ac 0 | Out-Null
    powercfg /change disk-timeout-dc 0 | Out-Null

    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_SLEEP -Set STANDBYIDLE -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_SLEEP -Set HIBERNATEIDLE -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_SLEEP -Set HYBRIDSLEEP -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_SLEEP -Set RTCWAKE -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_VIDEO -Set VIDEOIDLE -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_DISK -Set DISKIDLE -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_BUTTONS -Set LIDACTION -Val 0
    Set-DevelopEnvPowerBoth -Scheme $scheme -Sub SUB_PCIEXPRESS -Set ASPM -Val 0
    powercfg /setactive $scheme | Out-Null

    reg add "HKCU\Control Panel\Desktop" /v ScreenSaveActive /t REG_SZ /d 0 /f | Out-Null

    Write-InstallStep "Always-on power: never idle sleep/hibernate/display/disk (scheme $scheme)"
}

function Test-DevelopEnvNeverSleep {
    # True when AC standby timeout is 0 (never) on the active scheme.
    $schemeLine = powercfg /getactivescheme
    if ($schemeLine -notmatch '([0-9a-f-]{36})') { return $false }
    $scheme = $Matches[1]
    $query = powercfg /query $scheme SUB_SLEEP STANDBYIDLE 2>&1 | Out-String
    # Current AC Power Setting Index: 0x00000000 means never.
    return [bool]($query -match 'Current AC Power Setting Index:\s*0x0+\b')
}
