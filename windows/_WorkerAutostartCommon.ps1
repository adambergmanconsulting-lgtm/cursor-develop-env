# Shared helpers for Cursor My Machines Windows autostart installers.

function Write-InstallStep {
    param([string] $Message)
    Write-Host $Message
}

function Get-AgentCmdPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\agent.cmd'
}

function Get-DefaultAutostartLogPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\worker-autostart.log'
}

function Get-DefaultStartScriptPath {
    Join-Path $env:LOCALAPPDATA 'cursor-agent\start-my-machines-worker.ps1'
}

function Ensure-GitBash {
    $git = Get-Command git -ErrorAction SilentlyContinue
    if (-not $git) {
        throw @"
Git for Windows is required (includes Git Bash).
Install from https://git-scm.com/download/win then re-run this script.
"@
    }
    $bashCandidates = @(
        (Join-Path (Split-Path $git.Source -Parent) 'bash.exe'),
        'C:\Program Files\Git\bin\bash.exe',
        'C:\Program Files (x86)\Git\bin\bash.exe'
    )
    foreach ($bash in $bashCandidates) {
        if (Test-Path -LiteralPath $bash) { return }
    }
    throw 'Git is on PATH but Git Bash was not found. Reinstall Git for Windows with Git Bash.'
}

function Ensure-AgentCli {
    param([string] $AgentCmd)

    if (Test-Path -LiteralPath $AgentCmd) { return }
    Write-InstallStep 'Cursor CLI not found. Installing via cursor.com/install (win32)...'
    irm 'https://cursor.com/install?win32=true' | iex
    if (-not (Test-Path -LiteralPath $AgentCmd)) {
        throw "Install finished but agent.cmd is missing at $AgentCmd. Open a new terminal and run: agent --version"
    }
}

function Test-AgentAuth {
    param([string] $AgentCmd)

    $debug = & $AgentCmd worker debug 2>&1 | Out-String
    if ($debug -match 'Auth\s+Method\s+login' -or $debug -match 'Auth\s+Method\s+api-key' -or $debug -match 'Auth\s+Method\s+token') {
        return
    }
    if ($debug -match 'not authenticated|sign in|login required') {
        throw 'Cursor CLI is not signed in. Run: agent login'
    }
    if ($debug -notmatch 'Email\s+\S') {
        throw 'Could not verify Cursor login. Run: agent login'
    }
}

function Write-WorkerStartScript {
    param(
        [string] $Path,
        [string] $Agent,
        [string] $Root,
        [string] $Name,
        [string] $Log,
        [string] $ScopeNote
    )

    $content = @"
# Generated by cursor-my-machines installer ($ScopeNote).
`$ErrorActionPreference = 'Stop'

`$agentCmd = '$Agent'
`$workerRoot = '$Root'
`$workerName = '$Name'
`$logPath = '$Log'

function Write-AutostartLog {
    param([string]`$Message)
    `$line = "{0} {1}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), `$Message
    Add-Content -LiteralPath `$logPath -Value `$line -Encoding utf8
}

if (-not (Test-Path -LiteralPath `$agentCmd)) {
    Write-AutostartLog "agent.cmd missing at `$agentCmd"
    exit 1
}

if (-not (Test-Path -LiteralPath `$workerRoot)) {
    Write-AutostartLog "worker root missing at `$workerRoot"
    exit 1
}

`$running = Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
    Where-Object { `$_.CommandLine -like '*cursor-agent*' -and `$_.CommandLine -like '*worker*' }
if (`$running) {
    Write-AutostartLog "worker already running (pid `$(`$running.ProcessId -join ',')); skipping"
    exit 0
}

Write-AutostartLog "starting worker name=`$workerName root=`$workerRoot"
Set-Location -LiteralPath `$workerRoot
& `$agentCmd worker --name `$workerName --worker-dir `$workerRoot start
`$exit = `$LASTEXITCODE
Write-AutostartLog "worker exited with code `$exit"
exit `$exit
"@

    Set-Content -LiteralPath $Path -Value $content -Encoding utf8
}

function Register-WorkerAutostartTask {
    param(
        [string] $Name,
        [string] $ScriptPath,
        [string] $Description
    )

    $pwsh = (Get-Command pwsh -ErrorAction SilentlyContinue)?.Source
    if (-not $pwsh) {
        $pwsh = (Get-Command powershell.exe).Source
    }

    $action = New-ScheduledTaskAction -Execute $pwsh -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$ScriptPath`""
    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
    $settings = New-ScheduledTaskSettingsSet `
        -AllowStartIfOnBatteries `
        -DontStopIfGoingOnBatteries `
        -ExecutionTimeLimit ([TimeSpan]::Zero) `
        -RestartCount 999 `
        -RestartInterval (New-TimeSpan -Minutes 5) `
        -MultipleInstances IgnoreNew
    $principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

    $existing = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if ($existing) {
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false
    }

    Register-ScheduledTask `
        -TaskName $Name `
        -Action $action `
        -Trigger $trigger `
        -Settings $settings `
        -Principal $principal `
        -Description $Description | Out-Null
}

function Uninstall-WorkerAutostartTask {
    param([string] $Name)

    $existing = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if ($existing) {
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false
        Write-InstallStep "Removed scheduled task: $Name"
    } else {
        Write-InstallStep "Scheduled task not found: $Name"
    }
}
